// Local development chain setup, used by scripts/localnet.sh.
//
//   init                      create a test USDC mint and initialize the platform
//   fund <wallet> [usdc]      airdrop SOL and mint test USDC to a wallet
//
// Everything it creates is for the throwaway local validator only. The keys it
// writes under .localnet/ (git-ignored) control nothing anywhere else.

import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { createMint, mintTo } from '@solana/spl-token';
import { Connection, Keypair, PublicKey } from '@solana/web3.js';
import {
  createTaskraConfig,
  createUsdcAccountIdempotent,
  fetchPlatform,
  findAssociatedTokenAddress,
} from '@taskra/sdk';
import {
  airdrop,
  initializePlatformOnChain,
  loadKeypair,
  requireEnv,
  send,
} from '../../../packages/sdk/e2e/lib.js';

// The devnet-demo profile of docs/13-DECISIONS.md §15: windows of minutes, so a
// review expiry or a dispute can be shown live. Never for real funds.
const PROFILE = { feeBps: 250, reviewWindow: 600n, verificationGrace: 300n, disputeTimeout: 900n };

const ROOT = fileURLToPath(new URL('../../../.localnet/', import.meta.url));
const KEYS = `${ROOT}keys/`;
const rpcUrl = process.env['RPC_URL'] ?? 'http://127.0.0.1:8899';
const connection = new Connection(rpcUrl, 'confirmed');

function key(name: string): Keypair {
  const path = `${KEYS}${name}.json`;
  if (existsSync(path)) return loadKeypair(path);
  mkdirSync(KEYS, { recursive: true, mode: 0o700 });
  const keypair = Keypair.generate();
  writeFileSync(path, JSON.stringify([...keypair.secretKey]), { mode: 0o600 });
  return keypair;
}

async function init(): Promise<void> {
  const upgradeAuthority = loadKeypair(requireEnv('TASKRA_UPGRADE_AUTHORITY_KEYPAIR'));
  const authority = key('platform-authority');
  const attester = key('attester');
  const treasuryOwner = key('treasury-owner');
  const mintAuthority = key('mint-authority');
  for (const wallet of [upgradeAuthority, authority, attester, mintAuthority]) {
    await airdrop(connection, wallet.publicKey, 10);
  }
  const mint = await createMint(
    connection,
    mintAuthority,
    mintAuthority.publicKey,
    null,
    6,
    undefined,
    {
      commitment: 'confirmed',
    },
  );
  const config = createTaskraConfig({ cluster: 'localnet', usdcMint: mint });
  await send(
    connection,
    'create the treasury token account',
    [
      createUsdcAccountIdempotent(config, {
        payer: mintAuthority.publicKey,
        owner: treasuryOwner.publicKey,
      }),
    ],
    [mintAuthority],
    'confirmed',
  );
  await initializePlatformOnChain(connection, config, upgradeAuthority, {
    treasury: findAssociatedTokenAddress(treasuryOwner.publicKey, mint),
    authority: authority.publicKey,
    attester: attester.publicKey,
    ...PROFILE,
  });
  const platform = await fetchPlatform(connection, config, 'finalized');

  const program = config.programId.toBase58();
  const lines = [
    '# Local validator values. Copy these over the matching lines of .env.',
    '# Generated by scripts/localnet.sh; valid only while that validator runs.',
    'SOLANA_NETWORK=localnet',
    `SOLANA_RPC_URL=${rpcUrl}`,
    `TASKRA_PROGRAM_ID=${program}`,
    `USDC_MINT=${mint.toBase58()}`,
    'NEXT_PUBLIC_SOLANA_NETWORK=localnet',
    `NEXT_PUBLIC_SOLANA_RPC_URL=${rpcUrl}`,
    `NEXT_PUBLIC_TASKRA_PROGRAM_ID=${program}`,
    `NEXT_PUBLIC_USDC_MINT=${mint.toBase58()}`,
    '# Local test key only. On any shared deployment this belongs in the',
    "# attestation service's own secret store, never next to the API's variables.",
    `ATTESTER_SECRET_KEY=${JSON.stringify([...attester.secretKey])}`,
    '',
  ];
  writeFileSync(`${ROOT}env`, lines.join('\n'), { mode: 0o600 });
  writeFileSync(`${ROOT}mint`, mint.toBase58());

  console.log('\nLocal platform ready');
  console.log(`  program             ${program}`);
  console.log(`  test USDC mint      ${mint.toBase58()}`);
  console.log(`  platform authority  ${platform.authority.toBase58()}`);
  console.log(`  attester            ${platform.attester.toBase58()}`);
  console.log(
    `  windows             review ${String(PROFILE.reviewWindow)} s, grace ${String(PROFILE.verificationGrace)} s, dispute ${String(PROFILE.disputeTimeout)} s`,
  );
  console.log('  environment values  .localnet/env');
}

async function fund(wallet: string, usdc: string): Promise<void> {
  if (!/^\d{1,9}$/.test(usdc)) throw new Error('the amount must be a whole number of USDC');
  const owner = new PublicKey(wallet);
  const mint = new PublicKey(readFileSync(`${ROOT}mint`, 'utf8').trim());
  const mintAuthority = key('mint-authority');
  const config = createTaskraConfig({ cluster: 'localnet', usdcMint: mint });
  await airdrop(connection, owner, 5);
  await send(
    connection,
    'create the USDC account',
    [createUsdcAccountIdempotent(config, { payer: mintAuthority.publicKey, owner })],
    [mintAuthority],
    'confirmed',
  );
  await mintTo(
    connection,
    mintAuthority,
    mint,
    findAssociatedTokenAddress(owner, mint),
    mintAuthority,
    BigInt(usdc) * 1_000_000n,
    [],
    { commitment: 'confirmed' },
  );
  console.log(`\n${wallet} now has 5 more SOL and ${usdc} more test USDC on the local validator`);
}

const [command, ...rest] = process.argv.slice(2);
if (command === 'init') await init();
else if (command === 'fund' && rest[0] !== undefined) await fund(rest[0], rest[1] ?? '1000');
else {
  console.error('usage: localnet.ts init | fund <wallet> [usdc]');
  process.exit(2);
}
